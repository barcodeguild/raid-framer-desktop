private val lootBuffByIdMap = LOOT_BUFF_DEFINITIONS.associateBy { it.buffId }

fun lootBuffById(buffId: Int): LootBuffDefinition? = lootBuffByIdMap[buffId]

/**
 * Sums the loot-drop percentages of every loot buff present in [buffIds]. Unknown IDs
 * contribute nothing, so a player with no loot buffs returns 0.
 */
fun lootBuffAmountForIds(buffIds: Set<Int>): Int {
  return buffIds.sumOf { lootBuffByIdMap[it]?.lootPercent ?: 0 }
}