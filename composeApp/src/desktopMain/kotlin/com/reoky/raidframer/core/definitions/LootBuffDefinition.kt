package com.reoky.raidframer.core.definitions

/**
 * Metadata for a single loot buff: its numeric buff ID, display name, the loot-drop
 * percentage it contributes, and (when known) its duration in seconds. Buffs without
 * a recorded duration are treated as unlimited (null). eek
 *
 * The Kotlin side sums every loot buff a player currently has into a combined percentage
 * (see [lootBuffAmountForIds]) so the raid buff scanner can compare that total against a
 * user-configurable threshold instead of just "has at least one" / "has two".
 */
data class LootBuffDefinition(
  val buffId: Int,
  val name: String,
  val lootPercent: Int,
  val durationSeconds: Int? = null
)

